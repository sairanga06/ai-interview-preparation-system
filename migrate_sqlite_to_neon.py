from __future__ import annotations

import os
import sqlite3
from pathlib import Path
from typing import Any

import psycopg
from dotenv import load_dotenv


BASE_DIR = Path(__file__).resolve().parent
SQLITE_PATH = BASE_DIR / "interview.db"


def qident(name: str) -> str:
    return '"' + str(name).replace('"', '""') + '"'


def map_sqlite_type(sqlite_type: str | None) -> str:
    t = (sqlite_type or "").strip().upper()
    if "INT" in t:
        return "BIGINT"
    if any(x in t for x in ("REAL", "FLOA", "DOUB")):
        return "DOUBLE PRECISION"
    if "BLOB" in t:
        return "BYTEA"
    return "TEXT"


def normalize_default(default_value: Any) -> str | None:
    if default_value is None:
        return None
    raw = str(default_value).strip()
    if not raw:
        return None

    upper = raw.upper()
    if upper.startswith("(CURRENT_TIMESTAMP") or upper == "CURRENT_TIMESTAMP":
        return "CURRENT_TIMESTAMP"
    if upper.startswith("(CURRENT_DATE") or upper == "CURRENT_DATE":
        return "CURRENT_DATE"
    if upper.startswith("(CURRENT_TIME") or upper == "CURRENT_TIME":
        return "CURRENT_TIME"
    if upper in {"TRUE", "FALSE"}:
        return upper

    try:
        float(raw)
        return raw
    except ValueError:
        pass

    if len(raw) >= 2 and raw[0] == "'" and raw[-1] == "'":
        return raw

    return "'" + raw.replace("'", "''") + "'"


def get_sqlite_tables(conn: sqlite3.Connection) -> list[str]:
    rows = conn.execute(
        """
        SELECT name
        FROM sqlite_master
        WHERE type = 'table'
          AND name NOT LIKE 'sqlite_%'
        ORDER BY name
        """
    ).fetchall()
    return [row[0] for row in rows]


def get_sqlite_columns(conn: sqlite3.Connection, table: str) -> list[dict[str, Any]]:
    rows = conn.execute(f"PRAGMA table_info({qident(table)})").fetchall()
    return [
        {
            "name": row[1],
            "type": row[2] or "",
            "notnull": bool(row[3]),
            "default": row[4],
            "pk_ordinal": int(row[5] or 0),
        }
        for row in rows
    ]


def get_sqlite_foreign_keys(
    conn: sqlite3.Connection, table: str
) -> list[dict[str, Any]]:
    rows = conn.execute(f"PRAGMA foreign_key_list({qident(table)})").fetchall()
    return [
        {
            "id": int(row[0]),
            "seq": int(row[1]),
            "ref_table": row[2],
            "from_col": row[3],
            "to_col": row[4],
            "on_update": (row[5] or "NO ACTION").upper(),
            "on_delete": (row[6] or "NO ACTION").upper(),
        }
        for row in rows
    ]


def get_sqlite_indexes(
    conn: sqlite3.Connection, table: str
) -> list[dict[str, Any]]:
    rows = conn.execute(f"PRAGMA index_list({qident(table)})").fetchall()
    indexes = []

    for row in rows:
        index_name = row[1]
        is_unique = bool(row[2])
        partial = bool(row[4]) if len(row) > 4 else False

        if str(index_name).startswith("sqlite_autoindex_"):
            continue

        info_rows = conn.execute(
            f"PRAGMA index_info({qident(index_name)})"
        ).fetchall()
        columns = [r[2] for r in info_rows if len(r) >= 3 and r[2] is not None]

        indexes.append(
            {
                "name": index_name,
                "unique": is_unique,
                "partial": partial,
                "columns": columns,
            }
        )

    return indexes


def pg_user_tables(conn: psycopg.Connection) -> list[str]:
    rows = conn.execute(
        """
        SELECT table_name
        FROM information_schema.tables
        WHERE table_schema = 'public'
          AND table_type = 'BASE TABLE'
        ORDER BY table_name
        """
    ).fetchall()
    return [row[0] for row in rows]


def build_create_table_sql(
    table: str, columns: list[dict[str, Any]]
) -> tuple[str, list[str]]:
    pk_columns = [
        c["name"]
        for c in sorted(columns, key=lambda x: x["pk_ordinal"])
        if c["pk_ordinal"] > 0
    ]
    single_pk = pk_columns[0] if len(pk_columns) == 1 else None

    definitions = []
    identity_columns = []

    for c in columns:
        parts = [qident(c["name"]), map_sqlite_type(c["type"])]

        is_integer_identity = (
            single_pk == c["name"] and "INT" in (c["type"] or "").upper()
        )
        if is_integer_identity:
            parts.append("GENERATED BY DEFAULT AS IDENTITY")
            identity_columns.append(c["name"])

        if c["notnull"] and c["pk_ordinal"] == 0:
            parts.append("NOT NULL")

        default_sql = normalize_default(c["default"])
        if default_sql is not None:
            parts.append(f"DEFAULT {default_sql}")

        definitions.append(" ".join(parts))

    if pk_columns:
        definitions.append(
            "PRIMARY KEY (" + ", ".join(qident(x) for x in pk_columns) + ")"
        )

    sql = f"CREATE TABLE {qident(table)} (\n    " + ",\n    ".join(definitions) + "\n)"
    return sql, identity_columns


def add_unique_constraints(
    sqlite_conn: sqlite3.Connection,
    pg_conn: psycopg.Connection,
    table: str,
) -> int:
    rows = sqlite_conn.execute(f"PRAGMA index_list({qident(table)})").fetchall()
    created = 0

    for row in rows:
        index_name = row[1]
        if not bool(row[2]) or not str(index_name).startswith("sqlite_autoindex_"):
            continue

        info_rows = sqlite_conn.execute(
            f"PRAGMA index_info({qident(index_name)})"
        ).fetchall()
        columns = [r[2] for r in info_rows if len(r) >= 3 and r[2] is not None]
        if not columns:
            continue

        constraint_name = f"{table}_{created}_unique"
        sql = (
            f"ALTER TABLE {qident(table)} "
            f"ADD CONSTRAINT {qident(constraint_name)} UNIQUE ("
            + ", ".join(qident(c) for c in columns)
            + ")"
        )
        pg_conn.execute(sql)
        created += 1

    return created


def add_indexes(
    sqlite_conn: sqlite3.Connection,
    pg_conn: psycopg.Connection,
    table: str,
) -> int:
    created = 0

    for index in get_sqlite_indexes(sqlite_conn, table):
        if not index["columns"] or index["partial"]:
            continue

        sql = (
            "CREATE "
            + ("UNIQUE " if index["unique"] else "")
            + f"INDEX {qident(index['name'])} ON {qident(table)} ("
            + ", ".join(qident(c) for c in index["columns"])
            + ")"
        )
        pg_conn.execute(sql)
        created += 1

    return created


def add_foreign_keys(
    sqlite_conn: sqlite3.Connection,
    pg_conn: psycopg.Connection,
    table: str,
) -> int:
    grouped: dict[int, list[dict[str, Any]]] = {}
    for fk in get_sqlite_foreign_keys(sqlite_conn, table):
        grouped.setdefault(fk["id"], []).append(fk)

    created = 0
    for fk_id, items in sorted(grouped.items()):
        items.sort(key=lambda x: x["seq"])
        ref_table = items[0]["ref_table"]
        local_cols = [x["from_col"] for x in items]
        ref_cols = [x["to_col"] for x in items]

        actions = []
        if items[0]["on_delete"] != "NO ACTION":
            actions.append(f"ON DELETE {items[0]['on_delete']}")
        if items[0]["on_update"] != "NO ACTION":
            actions.append(f"ON UPDATE {items[0]['on_update']}")

        sql = (
            f"ALTER TABLE {qident(table)} "
            f"ADD CONSTRAINT {qident(f'fk_{table}_{fk_id}')} "
            f"FOREIGN KEY ("
            + ", ".join(qident(c) for c in local_cols)
            + f") REFERENCES {qident(ref_table)} ("
            + ", ".join(qident(c) for c in ref_cols)
            + ") "
            + " ".join(actions)
        )
        pg_conn.execute(sql)
        created += 1

    return created


def migrate() -> int:
    load_dotenv()

    if not SQLITE_PATH.exists():
        print(f"ERROR: {SQLITE_PATH} was not found.")
        return 1

    database_url = os.getenv("DATABASE_URL", "").strip()
    if not database_url.startswith(("postgresql://", "postgres://")):
        print("ERROR: DATABASE_URL is missing or invalid.")
        return 1

    print("CareerCraft AI — SQLite → Neon migration")
    print(f"Source database: {SQLITE_PATH.name}")

    sqlite_uri = f"file:{SQLITE_PATH.resolve().as_posix()}?mode=ro"
    sqlite_conn = sqlite3.connect(sqlite_uri, uri=True)
    sqlite_conn.execute("PRAGMA foreign_keys = ON")

    try:
        tables = get_sqlite_tables(sqlite_conn)
        print(f"Found {len(tables)} tables in SQLite:")
        for table in tables:
            count = sqlite_conn.execute(
                f"SELECT COUNT(*) FROM {qident(table)}"
            ).fetchone()[0]
            print(f"  {table}: {count} row(s)")

        pg_conn = psycopg.connect(database_url, connect_timeout=30)

        try:
            existing = pg_user_tables(pg_conn)
            if existing:
                print("\nSTOP: Neon is not empty.")
                print("Existing public tables:")
                for table in existing:
                    print(f"  {table}")
                print("\nNo Neon changes were made.")
                return 1

            print("\nNeon is empty. Creating tables...")

            identity_map: dict[str, list[str]] = {}

            for table in tables:
                columns = get_sqlite_columns(sqlite_conn, table)
                create_sql, identity_columns = build_create_table_sql(table, columns)
                pg_conn.execute(create_sql)
                identity_map[table] = identity_columns

            print("Tables created. Copying data...")

            for table in tables:
                columns = get_sqlite_columns(sqlite_conn, table)
                names = [c["name"] for c in columns]
                rows = sqlite_conn.execute(
                    f"SELECT {', '.join(qident(n) for n in names)} FROM {qident(table)}"
                ).fetchall()

                if not rows:
                    continue

                placeholders = ", ".join(["%s"] * len(names))
                insert_sql = (
                    f"INSERT INTO {qident(table)} ("
                    + ", ".join(qident(n) for n in names)
                    + f") VALUES ({placeholders})"
                )
                # psycopg 3 exposes executemany() through a cursor.
                with pg_conn.cursor() as cursor:
                    cursor.executemany(insert_sql, rows)

            print("Data copied. Restoring constraints and indexes...")

            for table in tables:
                add_unique_constraints(sqlite_conn, pg_conn, table)
                add_indexes(sqlite_conn, pg_conn, table)

            for table in tables:
                add_foreign_keys(sqlite_conn, pg_conn, table)

            for table, identity_columns in identity_map.items():
                for column in identity_columns:
                    max_id = pg_conn.execute(
                        f"SELECT MAX({qident(column)}) FROM {qident(table)}"
                    ).fetchone()[0]
                    if max_id is None:
                        continue

                    seq = pg_conn.execute(
                        "SELECT pg_get_serial_sequence(%s, %s)",
                        (f"public.{table}", column),
                    ).fetchone()[0]
                    if seq:
                        pg_conn.execute(
                            "SELECT setval(%s, %s, true)",
                            (seq, int(max_id)),
                        )

            pg_conn.commit()

            print("\n========================================")
            print("MIGRATION COMPLETED SUCCESSFULLY")
            print("========================================")
            print(f"Tables migrated: {len(tables)}")
            print("Original interview.db was not modified.")
            print("Neon migration committed.")
            return 0

        except Exception as exc:
            pg_conn.rollback()
            print("\n========================================")
            print("MIGRATION FAILED — ROLLED BACK")
            print("========================================")
            print(f"Reason: {exc}")
            print("Original interview.db was not modified.")
            return 1

        finally:
            pg_conn.close()

    finally:
        sqlite_conn.close()


if __name__ == "__main__":
    raise SystemExit(migrate())
